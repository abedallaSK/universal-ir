"""Generates values/, values-ar/ and values-iw/ strings.xml from tools/strings_source.py."""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from strings_source import S  # noqa: E402

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "app", "src", "main", "res")
TARGETS = (("values", 0), ("values-ar", 1), ("values-iw", 2))
ARG = re.compile(r"%\d+\$[sd]")


def escape(text):
    text = text.replace("\\", "\\\\").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    text = text.replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    if text.startswith("@") or text.startswith("?"):
        text = "\\" + text
    return text


def main():
    for key, values in S.items():
        args = [sorted(ARG.findall(v)) for v in values]
        if any(a != args[0] for a in args):
            sys.exit(f"Format arguments differ for {key}: {args}")
    for folder, idx in TARGETS:
        path = os.path.join(ROOT, folder)
        os.makedirs(path, exist_ok=True)
        lines = ['<?xml version="1.0" encoding="utf-8"?>',
                 "<!-- Generated by tools/gen_strings.py from tools/strings_source.py. Do not edit. -->",
                 "<resources>"]
        for key, values in S.items():
            extra = ""
            lines.append(f'    <string name="{key}"{extra}>{escape(values[idx])}</string>')
        lines.append("</resources>")
        with open(os.path.join(path, "strings.xml"), "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(lines) + "\n")
    print(f"wrote {len(S)} strings x {len(TARGETS)} locales")


if __name__ == "__main__":
    main()
