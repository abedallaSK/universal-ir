"""Generates values/, values-ar/ and values-iw/ strings.xml from tools/strings_source.py."""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from strings_source import S  # noqa: E402

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "app", "src", "main", "res")
TARGETS = (("values", 0), ("values-ar", 1), ("values-iw", 2))
ARG = re.compile(r"%\d+\$[sd]")


def escape(text):
    text = text.replace("\\", "\\\\").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    text = text.replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    if text.startswith("@") or text.startswith("?"):
        text = "\\" + text
    return text


def main():
    for key, values in S.items():
        args = [sorted(ARG.findall(v)) for v in values]
        if any(a != args[0] for a in args):
            sys.exit(f"Format arguments differ for {key}: {args}")
    for folder, idx in TARGETS:
        path = os.path.join(ROOT, folder)
        os.makedirs(path, exist_ok=True)
        lines = ['<?xml version="1.0" encoding="utf-8"?>',
                 "<!-- Generated by tools/gen_strings.py from tools/strings_source.py. Do not edit. -->",
                 "<resources>"]
        for key, values in S.items():
            extra = ""
            lines.append(f'    <string name="{key}"{extra}>{escape(values[idx])}</string>')
        lines.append("</resources>")
        with open(os.path.join(path, "strings.xml"), "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(lines) + "\n")
    # Extra languages: tools/strings_extra/<name>.py defines FOLDER (e.g. "values-fr") and K = {key: text}.
    # Missing keys fall back to English at runtime; format arguments must match the English text.
    import glob, importlib.util
    extra = 0
    for f in sorted(glob.glob(os.path.join(os.path.dirname(os.path.abspath(__file__)), "strings_extra", "*.py"))):
        spec = importlib.util.spec_from_file_location(os.path.basename(f)[:-3], f)
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        lines = ['<?xml version="1.0" encoding="utf-8"?>',
                 "<!-- Generated by tools/gen_strings.py from tools/strings_extra. Do not edit. -->",
                 "<resources>"]
        for key, text in mod.K.items():
            if key not in S:
                continue
            if sorted(ARG.findall(text)) != sorted(ARG.findall(S[key][0])):
                sys.exit(f"{f}: format arguments differ for {key}")
            lines.append(f'    <string name="{key}">{escape(text)}</string>')
        lines.append("</resources>")
        path = os.path.join(ROOT, mod.FOLDER)
        os.makedirs(path, exist_ok=True)
        with open(os.path.join(path, "strings.xml"), "w", encoding="utf-8", newline="\n") as out:
            out.write("\n".join(lines) + "\n")
        extra += 1
    print(f"wrote {len(S)} strings x {len(TARGETS)} locales + {extra} extra languages")


if __name__ == "__main__":
    main()
