// Release signing is read from keystore.properties (not committed). Without it the release
// build is produced unsigned so the configuration can be verified without secrets.
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}

android {
    namespace = "com.universalir"
    compileSdk = 36

    defaultConfig {
        applicationId = "com.universalir.remote"
        // ConsumerIrManager exists since API 19; 26 keeps adaptive icons, java.time and Compose
        // tooling simple while still covering every phone that ships an IR blaster today.
        minSdk = 26
        targetSdk = 36
        versionCode = 2
        versionName = "0.2.0"
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    signingConfigs {
        if (keystoreProps.isNotEmpty()) {
            create("release") {
                storeFile = rootProject.file(keystoreProps.getProperty("storeFile"))
                storePassword = keystoreProps.getProperty("storePassword")
                keyAlias = keystoreProps.getProperty("keyAlias")
                keyPassword = keystoreProps.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        debug {
            applicationIdSuffix = ".debug"
            versionNameSuffix = "-debug"
        }
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfigs.findByName("release")?.let { signingConfig = it }
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    kotlin {
        compilerOptions {
            jvmTarget.set(org.jetbrains.kotlin.gradle.dsl.JvmTarget.JVM_17)
        }
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }

    androidResources {
        generateLocaleConfig = false
    }

    sourceSets {
        getByName("androidTest").assets.srcDir("$projectDir/schemas")
    }

    packaging {
        resources.excludes += "/META-INF/{AL2.0,LGPL2.1}"
    }

    testOptions {
        unitTests.isReturnDefaultValues = true
    }
}

ksp {
    arg("room.schemaLocation", "$projectDir/schemas")
    arg("room.generateKotlin", "true")
}

// Ensure KSP cache & output directories exist before KSP tasks execute on Windows
tasks.matching { it.name.startsWith("ksp") }.configureEach {
    doFirst {
        layout.buildDirectory.dir("kspCaches/debug").get().asFile.mkdirs()
        layout.buildDirectory.dir("kspCaches/release").get().asFile.mkdirs()
        layout.buildDirectory.dir("generated/ksp/debug/java").get().asFile.mkdirs()
        layout.buildDirectory.dir("generated/ksp/release/java").get().asFile.mkdirs()
    }
}

