package com.universalir.data.local

import androidx.room.Entity
import androidx.room.ForeignKey
import androidx.room.Index
import androidx.room.PrimaryKey

@Entity(tableName = "brands", indices = [Index("normalizedName", unique = true)])
data class BrandEntity(
    @PrimaryKey val id: String,
    val name: String,
    val normalizedName: String,
    /** Comma separated DeviceCategory names this brand has code sets for. */
    val categories: String,
    val popular: Boolean = false,
)

@Entity(
    tableName = "brand_aliases",
    primaryKeys = ["brandId", "alias"],
    foreignKeys = [ForeignKey(BrandEntity::class, ["id"], ["brandId"], onDelete = ForeignKey.CASCADE)],
    indices = [Index("normalizedAlias")],
)
data class BrandAliasEntity(
    val brandId: String,
    val alias: String,
    val normalizedAlias: String,
    /** BCP-47 language of the alias: en, ar, he, zh. */
    val language: String,
)

@Entity(
    tableName = "device_models",
    foreignKeys = [ForeignKey(BrandEntity::class, ["id"], ["brandId"], onDelete = ForeignKey.CASCADE)],
    indices = [Index("brandId"), Index("normalizedModel"), Index("deviceType")],
)
data class DeviceModelEntity(
    @PrimaryKey val id: String,
    val brandId: String,
    val modelNumber: String,
    val normalizedModel: String,
    val deviceType: String,
    val region: String? = null,
    val protocolId: String? = null,
    val notes: String? = null,
)

@Entity(
    tableName = "code_sets",
    indices = [Index("protocolId"), Index("contentHash"), Index("brandId"), Index("category")],
)
data class CodeSetEntity(
    @PrimaryKey val id: String,
    val brandId: String,
    val category: String,
    val protocolId: String,
    /** PROTOCOL (generated by an encoder), ASSET (bundled file) or INLINE (canonical JSON). */
    val payloadKind: String,
    /** Asset path for ASSET, canonical JSON for INLINE, protocol options for PROTOCOL. */
    val rawPayload: String?,
    val payloadFormat: String,
    val carrierFrequencyHz: Int?,
    val formatVersion: Int = 1,
    val checksumMetadata: String? = null,
    val featureMetadata: String? = null,
    /** BUNDLED, IMPORTED or USER. */
    val origin: String,
    val contentHash: String? = null,
    val title: String,
    val commandCount: Int = 0,
)

@Entity(
    tableName = "remote_profiles",
    foreignKeys = [
        ForeignKey(DeviceModelEntity::class, ["id"], ["deviceModelId"], onDelete = ForeignKey.CASCADE),
        ForeignKey(CodeSetEntity::class, ["id"], ["codeSetId"], onDelete = ForeignKey.CASCADE),
    ],
    indices = [Index("deviceModelId"), Index("codeSetId"), Index("normalizedRemoteModel")],
)
data class RemoteProfileEntity(
    @PrimaryKey val id: String,
    val deviceModelId: String,
    val remoteModelNumber: String?,
    val normalizedRemoteModel: String?,
    val codeSetId: String,
    val protocolId: String,
    val sourceRepository: String,
    val sourceUrl: String,
    val licenseIdentifier: String,
    /** VerificationLevel name. */
    val verificationStatus: String,
    val evidence: String? = null,
    val lastUpdated: Long,
)

@Entity(
    tableName = "verifications",
    foreignKeys = [ForeignKey(CodeSetEntity::class, ["id"], ["codeSetId"], onDelete = ForeignKey.CASCADE)],
    indices = [Index("codeSetId")],
)
data class VerificationEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val codeSetId: String,
    val deviceModelId: String?,
    val testedPhone: String,
    val testedFunction: String,
    /** WORKED, NO_RESPONSE, PARTIAL. */
    val result: String,
    val timestamp: Long,
    val notes: String? = null,
)

@Entity(tableName = "rooms")
data class RoomEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val name: String,
    val icon: String,
    val color: Long,
    val sortOrder: Int,
)

@Entity(
    tableName = "saved_devices",
    foreignKeys = [
        ForeignKey(RoomEntity::class, ["id"], ["roomId"], onDelete = ForeignKey.SET_NULL),
        ForeignKey(CodeSetEntity::class, ["id"], ["codeSetId"], onDelete = ForeignKey.RESTRICT),
    ],
    indices = [Index("roomId"), Index("codeSetId")],
)
data class SavedDeviceEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val displayName: String,
    val category: String,
    val brandName: String,
    val modelId: String?,
    val codeSetId: String,
    val roomId: Long?,
    /** JSON: DeviceSettings (layout order, hidden buttons, AC state). */
    val customSettings: String,
    val favorite: Boolean,
    val sortOrder: Int,
    val createdAt: Long,
    val lastUsedAt: Long?,
)

@Entity(
    tableName = "favorite_commands",
    foreignKeys = [ForeignKey(SavedDeviceEntity::class, ["id"], ["deviceId"], onDelete = ForeignKey.CASCADE)],
    indices = [Index("deviceId")],
)
data class FavoriteCommandEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val deviceId: Long,
    val label: String,
    /** Command name for discrete remotes, or null when [acStateJson] is set. */
    val commandName: String?,
    val acStateJson: String?,
    val sortOrder: Int,
)

@Entity(tableName = "diagnostic_records")
data class DiagnosticRecordEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val timestamp: Long,
    val phone: String,
    val status: String,
    val carrierRanges: String,
    val detail: String?,
)
